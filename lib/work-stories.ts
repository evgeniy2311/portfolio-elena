/** История работы. Нет истории или она пустая — собирается из фактов работы, без цитат, которых не было. */
export function storyFor(work: Pick<Work, "slug" | "task" | "request" | "result">): WorkStory {
  const story = stories[work.slug];
  if (story && story.task.trim() && story.result.trim()) return story;
  return {
    task: work.request ? `${work.task} «${work.request}»` : work.task,
    result: work.result,
  };
}

/** Дословный запрос из текста задачи, если он там есть. */
export function quoteOf(story: WorkStory): string | null {
  const match = story.task.match(/«([^»]+)»/);
  return match ? match[1] : null;
}
